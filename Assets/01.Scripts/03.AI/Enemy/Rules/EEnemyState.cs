namespace Shinshi.AI
{
    /// <summary> 일반 적의 행동 상태, 즉발 공격(근접)은 실행이 예고가 끝나는 틱에 끝나므로 상태로 남기지 않는다 </summary>
    public enum EEnemyState
    {
        // 유효한 생존 플레이어가 없어 제자리에서 기다린다
        Idle      = 0,
        // 타깃을 향해 이동하거나 공격 거리 안에서 다음 공격을 기다린다
        Chase     = 1,
        // 이동과 회전을 멈추고 방향을 고정한 채 예고 시간을 센다
        Telegraph = 2,
        // 타격 뒤 새 공격을 막는 시간
        Recover   = 3,
        // 모든 상태보다 우선하며 되돌아오지 않는다
        Dead      = 4,
        // 고정한 방향으로 이동하며 판정하는 구간, 돌진형만 쓴다
        Dash      = 5,
        // 예고 중 피해를 받아 공격이 취소되고 잠시 굳는 구간, 끝나면 바로 다시 공격할 수 있다
        Hit       = 6
    }
}
