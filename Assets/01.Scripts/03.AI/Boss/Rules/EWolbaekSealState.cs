namespace Shinshi.AI
{
    /// <summary> 월백 여우불 유도와 봉인 핵 기믹의 진행 단계 </summary>
    public enum EWolbaekSealState
    {
        // 아직 발동하지 않았다, 체력이 경계에 닿았어도 앞선 기믹이 끝나기를 기다리는 중이면 여기에 머문다
        Dormant,

        // 차례를 반복하는 중이다, 보스는 무적이다
        Active,

        // 성공했다, 보스 무적이 풀려 반격 시간을 받는다. 이 동안 일반 패턴 선택은 막힌다
        Counter,

        // 반격 시간이 끝났을 때 체력이 다음 경계에 멈춰 있어 다음 기믹이 이어받기를 기다린다, 보스는 무적이고 사망도 보류된다
        NextBoundaryPending,

        // 반격까지 마쳤거나 발동하지 않고 넘어갔다, 전투당 한 번이라 다시 발동하지 않는다
        Completed,

        // 시간 제한이 지났거나 파티가 전멸했다, 보스전 실패는 세션이 확정한다
        Failed,

        // 전장 정보가 없거나 핵 후보가 모자라 안전하게 멈췄다, 보스는 무적으로 남고 끝내는 방법은 정해지지 않았다
        Halted,

        // 사망이나 전투 종료로 멈췄다
        Stopped
    }
}
