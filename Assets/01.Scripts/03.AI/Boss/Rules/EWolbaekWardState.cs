namespace Shinshi.AI
{
    /// <summary> 월백 색 결계 기믹의 진행 단계 </summary>
    public enum EWolbaekWardState
    {
        // 아직 발동하지 않았다, 체력이 경계에 닿았어도 앞선 기믹이 끝나기를 기다리는 중이면 여기에 머문다
        Dormant,

        // 중앙 공동 결계에 필수 참가자 전원이 모여 연속 집결을 채우는 단계다, 보스는 무적이다
        Gather,

        // 새 지점의 색 결계가 나타나 자기 색 결계를 찾아 이동하는 시간이다, 보스는 무적이다
        Search,

        // 첫 광역 공격이 판정된 뒤 마지막 광역 공격이 끝날 때까지다, 보스는 무적이다. 이 동안 부활 요청은 다음 탐색 시작까지 보류된다
        Strike,

        // 세 번째 지점의 마지막 광역 공격을 통과해 성공했거나 발동하지 못하고 넘어갔다, 전투당 한 번이라 다시 발동하지 않는다
        Completed,

        // 필수 참가자가 모두 쓰러졌다, 보스전 실패는 세션이 확정한다
        Failed,

        // 전장 정보가 없거나 결계 후보가 모자라 안전하게 멈췄다, 보스는 무적으로 남고 끝내는 방법은 정해지지 않았다
        Halted,

        // 사망이나 전투 종료로 멈췄다
        Stopped
    }
}
